"""Copies the Loose Threads wordmark and element SVGs out of the design board
(design/directions/threads.html) into data/assets.js for the film page.
usage: python3 tools/assets.py"""
import json, re
from pathlib import Path

here = Path(__file__).resolve().parent.parent
board = (here.parent / "directions" / "threads.html").read_text()
el = re.search(r"^const EL = (\{.*\});$", board, re.M).group(1)
wm = re.search(r"^const WM = (\".*\");$", board, re.M).group(1)
EL, WM = json.loads(el), json.loads(wm)
keep = ["needle", "spool", "hoop", "thimble", "scissors", "pin"]
weave = re.findall(r'--weave: url\("(data:image/svg\+xml;base64,[^"]+)"\)', board)
out = {"WM": WM, "EL": {k: EL[k] for k in keep}, "WEAVE": {"light": weave[0], "dark": weave[1]}}
(here / "data" / "assets.js").write_text("// Generated by tools/assets.py from design/directions/threads.html\nwindow.ASSETS = " + json.dumps(out, ensure_ascii=False) + ";\n")
print("wordmark", len(WM), "bytes; elements", ", ".join(keep))
