"""Refreshes data/start-here.json and data/start-here.js from src/welcome.rs: the blocks of
the "Start here" guide, in order. The guide's threads (quotes, words, the Moon sketch) are
kept from the note the app wrote on a first run, since they change rarely.
usage: python3 tools/start_here.py"""
import json, re
from pathlib import Path

here = Path(__file__).resolve().parent.parent
src = (here.parent.parent / "src" / "welcome.rs").read_text()
body = src[src.index("pub fn first_run_note"):]
unesc = lambda s: re.sub(r"\\u\{([0-9a-fA-F]+)\}", lambda m: chr(int(m.group(1), 16)), s).replace('\\"', '"').replace("\\\\", "\\")
lets = {k: unesc(v) for k, v in re.findall(r'let (\w+) = "((?:[^"\\]|\\.)*)";', body)}
KIND = {"Title": "title", "H1": "h1", "H2": "h2", "H3": "h3", "P": "paragraph", "Bullet": "bullet", "Numbered": "numbered", "Quote": "quote"}
blocks = []
for kind, lit, name in re.findall(r'\((Title|H1|H2|H3|P|Bullet|Numbered|Quote), (?:"((?:[^"\\]|\\.)*)"|(\w+))\)', body):
    blocks.append({"kind": KIND[kind], "text": unesc(lit) if name == "" else lets[name]})
out = here / "data" / "start-here.json"
old = json.loads(out.read_text())
data = {"title": blocks[0]["text"], "blocks": blocks, "threads": old["threads"]}
out.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n")
(here / "data" / "start-here.js").write_text("// Generated by tools/start_here.py from src/welcome.rs: the Start here guide.\nwindow.START = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(len(blocks), "blocks;", len(data["threads"]), "threads")
