"""Copies the picked logo, Darn · Border (design/logo/round-2/darn-border), into
data/logo.js for the film's last shot: the icon in both lights and the wordmark, whose
i is dotted with a cross-stitch.
usage: python3 tools/logo.py"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent.parent
src = here.parent / "logo" / "round-2" / "darn-border"
out = {name: (src / f"{file}.svg").read_text() for name, file in [("icon", "icon"), ("iconDark", "icon-dark"), ("wordmark", "wordmark"), ("mark", "mark")]}
(here / "data" / "logo.js").write_text("// Generated by tools/logo.py from design/logo/round-2/darn-border (picked 6 Nov 2026)\nwindow.LOGO = " + json.dumps(out, ensure_ascii=False) + ";\n")
print({k: len(v) for k, v in out.items()})
