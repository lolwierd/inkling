"""Copies the picked logo, Initial (design/logo/03-initial: a satin-stitched i dotted with a
French knot), into data/logo.js for the film: the icon in both lights, the mark and the
wordmark. The film's last shot builds the dark icon, and its sidebar and Settings show the
wordmark, as the app does.
usage: python3 tools/logo.py"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent.parent
src = here.parent / "logo" / "03-initial"
out = {name: (src / f"{file}.svg").read_text() for name, file in [("icon", "icon"), ("iconDark", "icon-dark"), ("wordmark", "wordmark"), ("mark", "mark")]}
(here / "data" / "logo.js").write_text("// Generated by tools/logo.py from design/logo/03-initial (Initial, picked 7 Nov 2026)\nwindow.LOGO = " + json.dumps(out, ensure_ascii=False) + ";\n")
print({k: len(v) for k, v in out.items()})
