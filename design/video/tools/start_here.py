"""Refreshes data/start-here.json and data/start-here.js: the "Start here" guide as the
app writes it on a first run (src/welcome.rs `first_run_note`), blocks and threads, so
the film shows the real thing. Give it a notebook folder the app has just made, e.g. the
one `scripts/dev state` prints (a fresh notebook opens on the guide):

usage: python3 tools/start_here.py <notebook-dir>"""
import json
import sys
from pathlib import Path

here = Path(__file__).resolve().parent.parent
if len(sys.argv) != 2:
    sys.exit(__doc__)
notes = [json.loads(p.read_text()) for p in (Path(sys.argv[1]) / "notes").glob("*.json")]
guide = next((n for n in notes if n.get("first_run") or n.get("title") == "Start here"), None)
if guide is None:
    sys.exit(f"no Start here note in {sys.argv[1]}")


def kind(k):
    """The store's block kind, flattened for the film: check-done, check, callout-tip, code-rust."""
    if isinstance(k, str):
        return k
    (name, value), = k.items()
    if name == "check":
        return "check-done" if value else "check"
    return f"{name}-{value}" if value else name


blocks = [{"kind": kind(b["kind"]), "text": b["text"]} for b in guide["blocks"]]
threads = [
    {"kind": t["kind"], "side": t["side"], "mind_name": t["mind_name"], "quote": t["quote"], "drawing": t.get("drawing"),
     "messages": [{"role": m["role"], "text": m["text"]} for m in t["messages"]]}
    for t in guide["threads"]
]
data = {"title": blocks[0]["text"], "blocks": blocks, "threads": threads}
out = here / "data" / "start-here.json"
out.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n")
(here / "data" / "start-here.js").write_text("// Generated by tools/start_here.py from the app's own first-run note: the Start here guide.\nwindow.START = " + json.dumps(data, ensure_ascii=False) + ";\n")
print(len(blocks), "blocks;", len(threads), "threads")
